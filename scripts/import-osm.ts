/**
 * Turns an OpenStreetMap Overpass export into SQL that upgrades the schematic buildings to
 * real public footprints (© OpenStreetMap contributors, ODbL).
 *
 *   1. Download (in a browser or with curl):
 *      https://overpass-api.de/api/interpreter?data=[out:json];way["building"](around:700,40.1146,-75.1113);out tags geom;
 *   2. npx tsx scripts/import-osm.ts overpass.json > supabase/osm_footprints.sql
 *   3. Review the matches printed to stderr, then run the SQL in Supabase.
 *
 * Only ways whose OSM `name` matches a CampusFix building are used; nothing is guessed.
 */
import { readFileSync } from 'node:fs'
import { BUILDINGS } from '../src/data/seed'

interface Way {
  type: 'way'
  id: number
  tags?: Record<string, string>
  geometry?: { lat: number; lon: number }[]
}

const file = process.argv[2]
if (!file) {
  console.error('usage: tsx scripts/import-osm.ts <overpass.json>')
  process.exit(1)
}
const ways = (JSON.parse(readFileSync(file, 'utf8')).elements as Way[]).filter((e) => e.type === 'way' && e.geometry?.length)
const norm = (s: string) => s.toLowerCase().replace(/\b(building|hall|the)\b/g, '').replace(/[^a-z]/g, '')
const q = (s: string) => `'${s.replace(/'/g, "''")}'`

const out: string[] = ['-- Generated by scripts/import-osm.ts — building footprints © OpenStreetMap contributors (ODbL)', 'begin;']
for (const b of BUILDINGS) {
  const aliases = [b.name, b.shortName, b.slug === 'athletic' ? 'Physical Education Building' : ''].filter(Boolean).map(norm)
  const matches = ways.filter((w) => w.tags?.name && aliases.includes(norm(w.tags.name)))
  if (!matches.length) {
    console.error(`no OSM match for ${b.name} — keeps schematic shape`)
    continue
  }
  const polys = matches.map((w) => [w.geometry!.map((p) => [p.lon, p.lat])])
  const pts = polys.flatMap((p) => p[0])
  const lng = pts.reduce((s, p) => s + p[0], 0) / pts.length
  const lat = pts.reduce((s, p) => s + p[1], 0) / pts.length
  const levels = Number(matches[0].tags?.['building:levels'])
  const height = Number(matches[0].tags?.height) || (levels ? levels * 3.6 : null)
  const geo = { type: 'MultiPolygon', coordinates: polys }
  console.error(`${b.name} ← ${matches.map((m) => `way/${m.id} "${m.tags!.name}"`).join(', ')}`)
  out.push(
    `update public.buildings set footprint_geojson = ${q(JSON.stringify(geo))}::jsonb, latitude = ${lat.toFixed(7)}, longitude = ${lng.toFixed(7)}, geo_source = ${q(matches.map((m) => `osm:way/${m.id}`).join(','))}${height ? `, height_m = ${height.toFixed(1)}` : ''} where id = ${q(b.id)};`,
  )
}
out.push('commit;')
console.log(out.join('\n'))
